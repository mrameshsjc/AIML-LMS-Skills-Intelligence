"""
Prepare a Hugging Face Space folder for the public demo (Phase 19).

NOTE (November 2026): Hugging Face now requires a PRO plan for Docker Spaces. The free
public demo uses Streamlit Community Cloud + Render instead (docs/PUBLIC_DEPLOYMENT_GUIDE.md).
This script is kept for anyone with a PRO plan.

A Hugging Face Docker Space is its own small Git repository with a Dockerfile
and a README.md whose header tells Hugging Face how to run it. This script
builds that folder from the project, for one of two Spaces:

    dashboard   the Streamlit dashboard  -> the PUBLIC DASHBOARD URL
    api         FastAPI + Swagger UI     -> the API BASE URL and SWAGGER URL

What it changes compared with the normal image (Dockerfile):
    - user ID 1000 (Hugging Face runs every container as user 1000)
    - the service's command on port 7860 (the port Hugging Face exposes)
    - public-demo defaults: login on + guest access, SQLite database, first
      model trained at start, TF-IDF search, labelled fallback LLM, framing
      allowed for the huggingface.co page
    Secrets are NOT in the folder: set them in the Space settings (see the guide).

HOW TO RUN (PowerShell, from the project folder)
    PS> python scripts/prepare_hf_space.py dashboard --out ..\\hf-lms-dashboard
    PS> python scripts/prepare_hf_space.py api --out ..\\hf-lms-api
    Then upload each folder:  hf upload <user>/<space> <folder> . --repo-type space
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PORT = 7860
COPY = [
    "requirements.txt",
    ".dockerignore",
    "app",
    "data/sample",
    "documents",
    "scripts",
    "dashboard",
    ".streamlit",
]
SKIP = shutil.ignore_patterns("__pycache__", "*.pyc", ".pytest_cache")

COMMANDS = {
    "dashboard": [
        "streamlit", "run", "dashboard/Home.py", f"--server.port={PORT}", "--server.address=0.0.0.0",
        "--server.headless=true", "--browser.gatherUsageStats=false",
    ],
    # --proxy-headers: behind the Hugging Face proxy, read the visitor's address (for rate limits)
    "api": [
        "uvicorn", "app.main:app", "--host", "0.0.0.0", "--port", str(PORT),
        "--proxy-headers", "--forwarded-allow-ips", "*",
    ],
}  # fmt: skip

# Safe defaults for a public demo. Space "Variables" override them; "Secrets" add the private values.
DEMO_ENV = {
    "APP_PROFILE": "public-demo",
    "AUTH_ENABLED": "true",
    "GUEST_ACCESS": "true",
    "DATA_SOURCE": "database",
    "DATABASE_URL": "sqlite:///./data/db/lms_ai.db",
    "USERS_FILE": "data/accounts/users.json",
    "PREPARE_TRAIN_MODEL": "true",
    "MLFLOW_ENABLED": "false",
    "EMBEDDING_PROVIDER": "tfidf",
    "LLM_PROVIDER": "fallback",
    "FRAME_ANCESTORS": "https://huggingface.co",
    "RATE_LIMIT_PER_MINUTE": "60",
    "RATE_LIMIT_CHAT_PER_MINUTE": "10",
    "RATE_LIMIT_ADMIN_PER_HOUR": "10",
    "RAG_MAX_UPLOAD_MB": "2",
}

TITLES = {"dashboard": "LMS Skills Intelligence", "api": "LMS Skills Intelligence API"}
DESCRIPTIONS = {  # Hugging Face allows at most 60 characters
    "dashboard": "LMS skills gaps, learning paths and a RAG assistant",
    "api": "FastAPI + Swagger UI for the LMS skills engine",
}


def space_dockerfile(service: str) -> str:
    """The project Dockerfile, adapted for a Hugging Face Space."""
    text = (ROOT / "Dockerfile").read_text(encoding="utf-8")
    text, n = re.subn(r"^ARG APP_UID=\d+$", "ARG APP_UID=1000", text, flags=re.MULTILINE)
    if n != 1:
        raise RuntimeError("Dockerfile: 'ARG APP_UID=...' not found")
    # Hugging Face checks the port itself; the image's API health check would be wrong for the dashboard.
    text = re.sub(r"^HEALTHCHECK [^\n]*\\\n[^\n]*\n", "", text, flags=re.MULTILINE)
    env = " \\\n    ".join(f'{k}="{v}"' for k, v in DEMO_ENV.items())
    cmd = "[" + ", ".join(f'"{part}"' for part in COMMANDS[service]) + "]"
    text, n = re.subn(
        r"^CMD \[.*\]$",
        f"# Public demo defaults (Phase 19)\nENV {env}\n\nCMD {cmd}",
        text,
        flags=re.MULTILINE,
    )
    if n != 1:
        raise RuntimeError("Dockerfile: CMD line not found")
    text = text.replace("EXPOSE 8000 8501 5000", f"EXPOSE {PORT}")
    note = f"# GENERATED by scripts/prepare_hf_space.py ({service} Space): edit the project Dockerfile.\n"
    first, rest = text.split("\n", 1)  # "# syntax=..." must stay the very first line
    return f"{first}\n{note}{rest}"


def space_readme(service: str) -> str:
    template = (ROOT / "deployment/cloud/huggingface" / f"README.{service}.md").read_text(encoding="utf-8")
    front = "\n".join(
        [
            "---",
            f"title: {TITLES[service]}",
            "emoji: 🎓",
            "colorFrom: blue",
            "colorTo: indigo",
            "sdk: docker",
            f"app_port: {PORT}",
            "pinned: false",
            f"short_description: {DESCRIPTIONS[service]}",
            "---",
            "",
        ]
    )
    return front + template


def build(service: str, out: Path) -> list[str]:
    if out.resolve() == ROOT.resolve() or ROOT.resolve() in out.resolve().parents:
        raise ValueError("--out must be a folder OUTSIDE the project (it becomes its own Git repository).")
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for item in COPY:
        source, target = ROOT / item, out / item
        if target.is_dir():
            shutil.rmtree(target)
        if source.is_dir():
            shutil.copytree(source, target, ignore=SKIP)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
        written.append(item)
    (out / "Dockerfile").write_text(space_dockerfile(service), encoding="utf-8", newline="\n")
    (out / "README.md").write_text(space_readme(service), encoding="utf-8", newline="\n")
    return [*written, "Dockerfile", "README.md"]


def main() -> None:
    parser = argparse.ArgumentParser(description="Prepare a Hugging Face Space folder (Phase 19).")
    parser.add_argument("service", choices=sorted(COMMANDS))
    parser.add_argument(
        "--out", required=True, type=Path, help="folder outside the project, e.g. ..\\hf-lms-api"
    )
    args = parser.parse_args()
    try:
        files = build(args.service, args.out)
    except (ValueError, RuntimeError) as error:
        sys.exit(str(error))
    print(f"Prepared the {args.service} Space in {args.out.resolve()}:")
    print("  " + ", ".join(files))
    print(
        "\nNext: set the Space secrets, then push this folder (docs/PUBLIC_DEPLOYMENT_GUIDE.md, section 4)."
    )


if __name__ == "__main__":
    main()
